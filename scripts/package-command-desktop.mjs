/** Freeze the native allowlist/presentation modules from the sole catalog owner. */
import fs from 'node:fs'
import { COMMAND_CATALOG, PRACTICE_AREAS } from '../lib/pt/catalog.ts'
import { CADENCE } from '../lib/pt/contract.ts'
const out = new URL('../../desktop/mp.preciadoTech.command/', import.meta.url)
const write = (file, value) => fs.writeFileSync(new URL(file, out), value)
write('catalog.json', JSON.stringify({ commands: COMMAND_CATALOG, practiceAreas: PRACTICE_AREAS }, null, 2) + '\n')
write('cadence.json', JSON.stringify(CADENCE.command) + '\n')
for (const file of ['command-display.mjs', 'presentation-state.mjs']) write(file, fs.readFileSync(new URL('../lib/pt/' + file, import.meta.url)))
const actions = Object.fromEntries(COMMAND_CATALOG.map(c => [c.desktopActionId, { path: c.webPath, enabled: c.enabled }]))
write('ActionMap.js', `.pragma library
// GENERATED by scripts/package-command-desktop.mjs; edit lib/pt/catalog.ts.
var actions = ${JSON.stringify(actions)};
function target(actionId, path, origin, enabled, validUntil, now) {
    var local = actions[actionId];
    if (!local || !local.enabled || !enabled || local.path !== path || !(now < Date.parse(validUntil))) return "";
    if (!/^https?:\\/\\/[^/?#@\\s]+$/.test(origin)) return "";
    return origin + local.path;
}
`)
